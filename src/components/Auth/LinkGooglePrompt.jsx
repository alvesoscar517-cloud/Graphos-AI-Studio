import { useState } from 'react'
import { useTranslation } from 'react-i18next'
import './LinkGooglePrompt.css'

const LinkGooglePrompt = ({ onLink, onClose }) => {
  const { t } = useTranslation()
  const [isLinking, setIsLinking] = useState(false)

  const handleLink = async () => {
    setIsLinking(true)
    try {
      await onLink()
    } finally {
      setIsLinking(false)
    }
  }

  return (
    <div className="link-google-overlay" onClick={onClose}>
      <div className="link-google-modal" onClick={(e) => e.stopPropagation()}>
        <button className="link-google-close" onClick={onClose}>
          <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
            <line x1="18" y1="6" x2="6" y2="18"></line>
            <line x1="6" y1="6" x2="18" y2="18"></line>
          </svg>
        </button>
        
        <div className="link-google-icon">
          <svg width="56" height="56" viewBox="0 0 87.3 78" xmlns="http://www.w3.org/2000/svg">
            <path d="m6.6 66.85 3.85 6.65c.8 1.4 1.95 2.5 3.3 3.3l13.75-23.8h-27.5c0 1.55.4 3.1 1.2 4.5z" fill="#0066da"/>
            <path d="m43.65 25-13.75-23.8c-1.35.8-2.5 1.9-3.3 3.3l-25.4 44a9.06 9.06 0 0 0 -1.2 4.5h27.5z" fill="#00ac47"/>
            <path d="m73.55 76.8c1.35-.8 2.5-1.9 3.3-3.3l1.6-2.75 7.65-13.25c.8-1.4 1.2-2.95 1.2-4.5h-27.502l5.852 11.5z" fill="#ea4335"/>
            <path d="m43.65 25 13.75-23.8c-1.35-.8-2.9-1.2-4.5-1.2h-18.5c-1.6 0-3.15.45-4.5 1.2z" fill="#00832d"/>
            <path d="m59.8 53h-32.3l-13.75 23.8c1.35.8 2.9 1.2 4.5 1.2h50.8c1.6 0 3.15-.45 4.5-1.2z" fill="#2684fc"/>
            <path d="m73.4 26.5-12.7-22c-.8-1.4-1.95-2.5-3.3-3.3l-13.75 23.8 16.15 28h27.45c0-1.55-.4-3.1-1.2-4.5z" fill="#ffba00"/>
          </svg>
        </div>

        <h3 className="link-google-title">
          {t('auth.email.linkGoogleRequired', 'Link Google Account')}
        </h3>
        
        <p className="link-google-desc">
          {t('auth.email.linkGoogleDesc', 'To use Google Drive sync, please link your Google account first.')}
        </p>

        <button 
          className="link-google-btn"
          onClick={handleLink}
          disabled={isLinking}
        >
          <svg width="18" height="18" viewBox="0 0 18 18" fill="none">
            <path d="M17.64 9.2c0-.637-.057-1.251-.164-1.84H9v3.481h4.844c-.209 1.125-.843 2.078-1.796 2.717v2.258h2.908c1.702-1.567 2.684-3.874 2.684-6.615z" fill="#4285F4"/>
            <path d="M9 18c2.43 0 4.467-.806 5.956-2.18l-2.908-2.259c-.806.54-1.837.86-3.048.86-2.344 0-4.328-1.584-5.036-3.711H.957v2.332C2.438 15.983 5.482 18 9 18z" fill="#34A853"/>
            <path d="M3.964 10.71c-.18-.54-.282-1.117-.282-1.71s.102-1.17.282-1.71V4.958H.957C.347 6.173 0 7.548 0 9s.348 2.827.957 4.042l3.007-2.332z" fill="#FBBC05"/>
            <path d="M9 3.58c1.321 0 2.508.454 3.44 1.345l2.582-2.58C13.463.891 11.426 0 9 0 5.482 0 2.438 2.017.957 4.958L3.964 7.29C4.672 5.163 6.656 3.58 9 3.58z" fill="#EA4335"/>
          </svg>
          {isLinking 
            ? t('auth.email.linking', 'Linking...') 
            : t('auth.email.linkGoogle', 'Link Google Account')
          }
        </button>

        <button className="link-google-cancel" onClick={onClose}>
          {t('common.cancel') || 'Cancel'}
        </button>
      </div>
    </div>
  )
}

export default LinkGooglePrompt
